const amount = (value) => new Intl.NumberFormat("en-IN", {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
}).format(Number(value || 0));

const ascii = (value) => String(value ?? "")
  .normalize("NFKD")
  .replace(/[^\x20-\x7E]/g, "?");

const pdfText = (value) => ascii(value)
  .replaceAll("\\", "\\\\")
  .replaceAll("(", "\\(")
  .replaceAll(")", "\\)");

function makePdf(lines) {
  const commands = [];
  const write = (text, x, y, size = 10, bold = false) => {
    commands.push(`BT /F${bold ? 2 : 1} ${size} Tf 1 0 0 1 ${x} ${y} Tm (${pdfText(text)}) Tj ET`);
  };
  const rule = (y) => commands.push(`0.75 w 50 ${y} m 545 ${y} l S`);

  write("VESTATRACK CRM", 50, 795, 18, true);
  write("PAYSLIP", 470, 795, 14, true);
  rule(780);
  let y = 758;
  for (const line of lines) {
    if (line.rule) { rule(y); y -= 16; continue; }
    write(line.label, 50, y, line.heading ? 12 : 10, Boolean(line.heading));
    if (line.value !== undefined) write(line.value, 320, y, line.heading ? 12 : 10, Boolean(line.emphasis));
    y -= line.heading ? 24 : 19;
  }
  write("Generated by VestaTrack CRM", 50, 35, 8);

  const stream = commands.join("\n") + "\n";
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}endstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach((offset) => { pdf += `${String(offset).padStart(10, "0")} 00000 n \n`; });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}

export function createPayslipPdf(payment, transactions = []) {
  const deductions = Number(payment.lop_deduction || 0) + Number(payment.deduction_amount || 0) + Number(payment.advance_recovery || 0);
  const gross = Number(payment.gross_amount || 0)
    || Number(payment.basic_salary || 0) + Number(payment.allowance_amount || 0)
      + Number(payment.overtime_amount || 0) + Number(payment.reimbursement_amount || 0)
      + Number(payment.bonus_amount || 0);
  const latestTransaction = transactions.at(-1) || {};
  const lines = [
    { label: "Employee", value: payment.employee_name || payment.employee_id || "Employee" },
    { label: "Payroll month", value: String(payment.payroll_month || "").slice(0, 7) },
    { label: "Status", value: String(payment.status || "").replaceAll("_", " ").toUpperCase() },
    { rule: true },
    { label: "EARNINGS", heading: true },
    { label: "Basic salary", value: `INR ${amount(payment.basic_salary)}` },
    { label: "Allowances", value: `INR ${amount(payment.allowance_amount)}` },
    { label: "Approved overtime", value: `INR ${amount(payment.overtime_amount)}` },
    { label: "Expense reimbursements", value: `INR ${amount(payment.reimbursement_amount)}` },
    { label: "Bonus / incentives", value: `INR ${amount(payment.bonus_amount)}` },
    { label: "Gross earnings", value: `INR ${amount(gross)}`, emphasis: true },
    { rule: true },
    { label: "DEDUCTIONS", heading: true },
    { label: "LOP deduction", value: `INR ${amount(payment.lop_deduction)}` },
    { label: "Other deductions", value: `INR ${amount(payment.deduction_amount)}` },
    { label: "Salary advance recovery", value: `INR ${amount(payment.advance_recovery)}` },
    { label: "Total deductions", value: `INR ${amount(deductions)}`, emphasis: true },
    { rule: true },
    { label: "NET PAYABLE", value: `INR ${amount(payment.net_amount)}`, heading: true, emphasis: true },
    { label: "Paid amount", value: `INR ${amount(payment.paid_amount)}` },
    { label: "Remaining balance", value: `INR ${amount(payment.remaining_amount)}` },
    { rule: true },
    { label: "ATTENDANCE", heading: true },
    { label: "Present / absent days", value: `${payment.present_days || 0} / ${payment.absent_days || 0}` },
    { label: "Paid / unpaid leave", value: `${payment.paid_leave_days || 0} / ${payment.unpaid_leave_days || 0}` },
    { label: "Approved overtime hours", value: String(payment.overtime_hours || 0) },
    { label: "Last payment date", value: latestTransaction.payment_date || payment.payment_date || "-" },
    { label: "Payment method", value: String(latestTransaction.payment_method || payment.payment_method || "-").replaceAll("_", " ") },
    { label: "Transaction reference", value: latestTransaction.reference_number || payment.reference_number || "-" },
  ];
  return makePdf(lines);
}

export function downloadPayslipPdf(payment, transactions = []) {
  const blob = createPayslipPdf(payment, transactions);
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const employee = String(payment.employee_name || "employee").replace(/[^a-z0-9_-]+/gi, "-").replace(/^-|-$/g, "") || "employee";
  link.href = url;
  link.download = `VestaTrack-payslip-${employee}-${String(payment.payroll_month || "month").slice(0, 7)}.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
