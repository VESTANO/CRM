import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "../../../frontend/node_modules/@electric-sql/pglite/dist/index.js";
import { pgcrypto } from "../../../frontend/node_modules/@electric-sql/pglite/dist/contrib/pgcrypto.js";

const storeId = "00000000-0000-4000-8000-000000000011";
const actorId = "00000000-0000-4000-8000-000000000001";
const employeeId = "00000000-0000-4000-8000-000000000002";
const claimId = "00000000-0000-4000-8000-000000000201";
const advanceId = "00000000-0000-4000-8000-000000000301";
const migration = (name) => readFileSync(new URL(`../../migrations/${name}.sql`, import.meta.url), "utf8");

async function setup() {
  const db = new PGlite({ extensions: { pgcrypto } });
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema storage; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql as $$ select null::uuid $$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);`);
  await db.exec(migration("202611020001_crm_core"));
  await db.exec(`create table crm_stores(id uuid primary key,name text); alter table profiles add column store_id uuid references crm_stores;
    insert into crm_stores values('${storeId}','QA Store');`);
  await db.exec(migration("202611100003_user_designations"));
  await db.exec(`insert into auth.users values('${actorId}'),('${employeeId}');
    insert into profiles(id,employee_id,name,email,role,designation,store_id) values
      ('${actorId}','ADMIN','Payroll Admin','admin@example.test','admin','','${storeId}'),
      ('${employeeId}','EMP01','Employee','employee@example.test','employee','Sales','${storeId}');`);
  await db.exec(migration("202611060006_persist_business_store"));
  await db.exec(migration("202611100008_payroll_payments"));
  await db.exec(migration("202611110001_payroll_overtime_hours"));
  // Attendance is owned by the companion module in production. The payroll
  // migration extends this table, so the isolated payroll schema supplies its
  // stable contract without importing device/punch fixtures.
  await db.exec("create table attendance_leave_days(id bigint generated by default as identity primary key, user_id uuid not null, leave_date date not null);");
  await db.exec(migration("202611110002_complete_payroll_module"));
  await db.exec(migration("202611110003_payroll_sales_visit_expenses"));
  await db.exec(migration("202611110004_atomic_payroll_creation"));
  await db.exec(`insert into crm_expense_claims(id,store_id,employee_id,expense_date,category,amount,reimbursable,status)
    values('${claimId}','${storeId}','${employeeId}','2026-02-10','Travel',200,true,'approved');
    insert into crm_salary_advances(id,store_id,employee_id,requested_amount,approved_amount,remaining_amount,status)
    values('${advanceId}','${storeId}','${employeeId}',300,300,300,'approved');`);
  return db;
}

function payment(month = "2026-02-01") {
  return {
    employee_id: employeeId, payroll_month: month, basic_salary: 2600,
    gross_amount: 2800, reimbursement_amount: 200, expense_claim_amount: 200,
    net_amount: 2450, remaining_amount: 2450, lop_deduction: 100,
    advance_recovery: 250, status: "submitted", payment_method: "bank_transfer",
    calculation: { qa: true }, audit_details: { month: month.slice(0, 7), net: 2450 },
  };
}

async function create(db, options = {}) {
  const result = await db.query(
    "select (crm_create_payroll_payment($1,$2,$3::jsonb,$4::uuid[],$5::bigint[],$6::jsonb)).id as id",
    [storeId, actorId, JSON.stringify(options.payment || payment()), options.claimIds || [claimId], options.visitIds || [], JSON.stringify(options.repayments || [{ advance_id: advanceId, amount: 250 }])],
  );
  return result.rows[0]?.id;
}

const count = async (db, table) => Number((await db.query(`select count(*) n from ${table}`)).rows[0].n);

test("atomic payroll creation saves payment, approved reimbursement, advance recovery and audit together", async () => {
  const db = await setup();
  try {
    const id = await create(db);
    assert.ok(id);
    assert.equal(await count(db, "crm_payroll_payments"), 1);
    assert.equal(await count(db, "crm_payroll_expense_reimbursements"), 1);
    assert.equal(await count(db, "crm_payroll_advance_repayments"), 1);
    assert.equal(await count(db, "crm_payroll_audit"), 1);
    assert.equal((await db.query("select reimbursed_payment_id from crm_expense_claims where id=$1", [claimId])).rows[0].reimbursed_payment_id, id);
    assert.equal(Number((await db.query("select remaining_amount from crm_salary_advances where id=$1", [advanceId])).rows[0].remaining_amount), 50);
  } finally { await db.close(); }
});

test("a failure after the payment insert rolls back every payroll financial write", async () => {
  const db = await setup();
  try {
    // The duplicate claim makes the second loop iteration fail after the
    // payment and first reimbursement would have been written.
    await assert.rejects(create(db, { claimIds: [claimId, claimId] }), /eligible|duplicate/i);
    assert.equal(await count(db, "crm_payroll_payments"), 0);
    assert.equal(await count(db, "crm_payroll_expense_reimbursements"), 0);
    assert.equal(await count(db, "crm_payroll_advance_repayments"), 0);
    assert.equal(await count(db, "crm_payroll_audit"), 0);
    assert.equal((await db.query("select reimbursed_payment_id from crm_expense_claims where id=$1", [claimId])).rows[0].reimbursed_payment_id, null);
    assert.equal(Number((await db.query("select remaining_amount from crm_salary_advances where id=$1", [advanceId])).rows[0].remaining_amount), 300);
  } finally { await db.close(); }
});

test("the monthly unique constraint rejects duplicate payroll generation without corrupting sources", async () => {
  const db = await setup();
  try {
    await create(db);
    await assert.rejects(create(db), /duplicate key|unique/i);
    assert.equal(await count(db, "crm_payroll_payments"), 1);
    assert.equal(await count(db, "crm_payroll_expense_reimbursements"), 1);
    assert.equal(Number((await db.query("select remaining_amount from crm_salary_advances where id=$1", [advanceId])).rows[0].remaining_amount), 50);
  } finally { await db.close(); }
});
