-- CRM data lives alongside the existing Vestano attendance schema, under its own
-- table and storage names. The browser talks to crm-api; direct table access is
-- deliberately denied to anon/authenticated roles.

create extension if not exists pgcrypto;

-- CRM accounts live in this project, separate from the Timesheet Supabase project.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  employee_id text not null unique,
  name text not null,
  email text not null unique,
  department text not null default 'Other',
  manager text not null default '',
  role text not null default 'employee' check (role in ('admin', 'super_admin', 'manager', 'employee')),
  active boolean not null default true,
  profile_image text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists crm_profiles_employee_search_idx on public.profiles (lower(employee_id));

alter table public.profiles enable row level security;
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
drop policy if exists crm_profiles_read_self on public.profiles;
create policy crm_profiles_read_self on public.profiles
  for select to authenticated using (id = auth.uid());

create or replace function public.resolve_login_email(identity text)
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select email
  from public.profiles
  where active
    and (lower(employee_id) = lower(trim(identity)) or lower(email) = lower(trim(identity)))
  order by employee_id
  limit 1;
$$;

revoke all on function public.resolve_login_email(text) from public;
grant execute on function public.resolve_login_email(text) to anon, authenticated;

create table if not exists public.crm_datasets (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete restrict,
  name text not null check (char_length(name) between 1 and 255),
  original_filename text not null,
  uploaded_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.crm_dataset_columns (
  id bigint generated by default as identity primary key,
  dataset_id bigint not null references public.crm_datasets(id) on delete cascade,
  sheet_name text not null,
  original_name text not null,
  field_key text not null,
  column_order integer not null check (column_order > 0),
  unique (dataset_id, sheet_name, field_key)
);

create table if not exists public.crm_customer_records (
  id bigint generated by default as identity primary key,
  dataset_id bigint not null references public.crm_datasets(id) on delete cascade,
  sheet_name text not null,
  row_number integer not null check (row_number > 0),
  original_data jsonb not null default '{}'::jsonb,
  response text not null default 'no_response'
    check (response in ('no_response', 'interested', 'not_interested', 'callback', 'converted')),
  note text not null default '',
  callback_date date,
  callback_completed_at timestamptz,
  callback_completed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dataset_id, sheet_name, row_number)
);

create table if not exists public.crm_customer_record_changes (
  id bigint generated by default as identity primary key,
  record_id bigint not null references public.crm_customer_records(id) on delete cascade,
  changed_by uuid references auth.users(id) on delete set null,
  previous_values jsonb not null default '{}'::jsonb,
  updated_values jsonb not null default '{}'::jsonb,
  changed_at timestamptz not null default now()
);

create table if not exists public.crm_manual_clients (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete restrict,
  client_name text not null check (char_length(client_name) between 1 and 255),
  phone text not null default '',
  email text not null default '',
  company text not null default '',
  location text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.crm_visits (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete restrict,
  customer_id bigint references public.crm_customer_records(id) on delete cascade,
  manual_client_id bigint references public.crm_manual_clients(id) on delete cascade,
  visit_date date not null,
  meeting_time time not null,
  location text not null,
  expense numeric(10, 2) not null default 0 check (expense >= 0),
  status text not null default 'healthy'
    check (status in ('healthy', 'follow_up_required', 'interested', 'not_interested', 'converted')),
  payment_status text not null default 'not_paid'
    check (payment_status in ('not_paid', 'partially_paid', 'completed', 'one_time')),
  total_amount numeric(12, 2) not null default 0 check (total_amount >= 0),
  paid_amount numeric(12, 2) not null default 0 check (paid_amount >= 0),
  payment_description text not null default '',
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((customer_id is not null and manual_client_id is null)
      or (customer_id is null and manual_client_id is not null))
);

create table if not exists public.crm_visit_images (
