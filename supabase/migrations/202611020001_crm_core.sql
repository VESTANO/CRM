create or replace function public.crm_set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'crm_datasets', 'crm_customer_records', 'crm_manual_clients', 'crm_visits',
    'crm_reminders', 'crm_assigned_tasks', 'crm_overtime_requests',
    'crm_push_subscriptions', 'crm_reminder_deliveries'
  ] loop
    execute format('drop trigger if exists %I on public.%I', table_name || '_updated_at', table_name);
    execute format('create trigger %I before update on public.%I for each row execute function public.crm_set_updated_at()', table_name || '_updated_at', table_name);
  end loop;
end;
$$;

