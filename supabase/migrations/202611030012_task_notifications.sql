-- Durable per-account task alerts. Only this table is readable through
-- Realtime; task data and images remain behind the CRM API.
create table public.crm_task_notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  task_id bigint not null references public.crm_assigned_tasks(id) on delete cascade,
  submission_id bigint references public.crm_task_submissions(id) on delete cascade,
  kind text not null check (kind in ('assigned', 'submitted', 'resubmitted', 'approved', 'rejected')),
  title text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (recipient_id, submission_id, kind)
);
create unique index crm_task_notification_assignment_idx on public.crm_task_notifications(recipient_id, task_id) where kind='assigned';
create index crm_task_notifications_inbox_idx on public.crm_task_notifications(recipient_id, id desc);
create index crm_task_notifications_unread_idx on public.crm_task_notifications(recipient_id) where read_at is null;
alter table public.crm_task_notifications enable row level security;
revoke all on public.crm_task_notifications from public, anon, authenticated;
grant select on public.crm_task_notifications to authenticated;
grant all on public.crm_task_notifications to service_role;
grant usage, select on sequence public.crm_task_notifications_id_seq to service_role;
create policy crm_task_notifications_read_own on public.crm_task_notifications for select to authenticated
  using (recipient_id = (select auth.uid()) and exists (select 1 from public.profiles where id=(select auth.uid()) and active));

create function public.crm_notify_task_assignment() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
begin
  insert into public.crm_task_notifications(recipient_id,task_id,kind,title,message)
  values(new.assignee_id,new.id,'assigned','New task assigned',format('You have been assigned "%s".',new.title))
  on conflict do nothing;
  return new;
end $$;
revoke all on function public.crm_notify_task_assignment() from public,anon,authenticated;
create trigger crm_task_assignment_notification after insert on public.crm_assigned_tasks
  for each row execute function public.crm_notify_task_assignment();

create function public.crm_notify_task_submission() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  task public.crm_assigned_tasks%rowtype;
  event_kind text; event_title text; event_message text; actor_name text;
  previous_reviewer uuid; recipients uuid[];
begin
  select * into task from public.crm_assigned_tasks where id=new.task_id;
  if tg_op='INSERT' then
    select reviewed_by into previous_reviewer from public.crm_task_submissions
      where task_id=new.task_id and id<new.id order by id desc limit 1;
    event_kind := case when exists(select 1 from public.crm_task_submissions where task_id=new.task_id and id<new.id) then 'resubmitted' else 'submitted' end;
    event_title := case when event_kind='resubmitted' then 'Task resubmitted for review' else 'Task submitted for review' end;
    select coalesce(employee_id,name,'User') into actor_name from public.profiles where id=new.submitted_by;
    event_message := format('%s %s "%s" for your review.',coalesce(actor_name,'User'),event_kind,task.title);
    -- Notify the assigning admin and, on rework, the previous reviewer. If
    -- neither account is available, the remaining active admins can pick it up.
    select array_agg(id) into recipients from public.profiles where active and role in ('admin','super_admin')
      and (id=task.assigned_by_id or id=previous_reviewer) and id is distinct from new.submitted_by;
    if coalesce(cardinality(recipients),0)=0 then
      select array_agg(id) into recipients from public.profiles where active and role in ('admin','super_admin') and id is distinct from new.submitted_by;
    end if;
    insert into public.crm_task_notifications(recipient_id,task_id,submission_id,kind,title,message)
    select recipient,new.task_id,new.id,event_kind,event_title,event_message from unnest(recipients) recipient
    on conflict do nothing;
  elsif old.status is distinct from new.status and new.status in ('approved','rejected') then
    event_title := case when new.status='approved' then 'Task approved' else 'Task rejected — changes needed' end;
    select coalesce(employee_id,name,'Admin') into actor_name from public.profiles where id=new.reviewed_by;
    event_message := format('"%s" was %s by %s.%s',task.title,new.status,coalesce(actor_name,'Admin'),
      case when new.review_note<>'' then ' ' || left(new.review_note,240) || case when char_length(new.review_note)>240 then '…' else '' end else '' end);
    insert into public.crm_task_notifications(recipient_id,task_id,submission_id,kind,title,message)
    values(task.assignee_id,new.task_id,new.id,new.status,event_title,event_message)
    on conflict do nothing;
  end if;
  return new;
end $$;
revoke all on function public.crm_notify_task_submission() from public,anon,authenticated;
create trigger crm_task_submission_notification after insert or update of status on public.crm_task_submissions
  for each row execute function public.crm_notify_task_submission();

alter publication supabase_realtime add table public.crm_task_notifications;
