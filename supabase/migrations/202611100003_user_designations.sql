-- Store-managed user designations. The Edge API remains the only browser
-- access path, so admins can manage options without direct table grants.
begin;

alter table public.profiles
  add column if not exists designation text not null default '';

create table if not exists public.crm_designations (
  id bigint generated by default as identity primary key,
  store_id uuid not null references public.crm_stores(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 80),
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles(id) on delete set null
);

create unique index if not exists crm_designations_store_name_unique
  on public.crm_designations(store_id, lower(name));
create index if not exists crm_designations_store_name_idx
  on public.crm_designations(store_id, name);

alter table public.crm_designations enable row level security;
revoke all on public.crm_designations from anon, authenticated;
grant select, insert, update, delete on public.crm_designations to service_role;

commit;
