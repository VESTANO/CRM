create table public.crm_task_submissions (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.crm_assigned_tasks(id) on delete cascade,
  submitted_by uuid references auth.users(id) on delete set null,
  note text not null default '' check (char_length(note) <= 4000),
  status text not null default 'submitted' check (status in ('submitted', 'approved', 'rejected')),
  submitted_at timestamptz not null default now(),
  review_note text not null default '' check (char_length(review_note) <= 4000),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  unique (id, task_id),
  check (status <> 'rejected' or char_length(trim(review_note)) > 0)
);
create index crm_task_submissions_task_idx on public.crm_task_submissions(task_id, id);
