-- Existing After photos have not yet been reviewed by an admin. Preserve them
-- as the first submission and place those tasks in the review queue.
insert into public.crm_task_submissions(task_id, submitted_by, submitted_at)
select task.id, task.assignee_id, coalesce(task.completed_at, max(image.uploaded_at))
from public.crm_assigned_tasks task join public.crm_task_images image on image.task_id = task.id
where image.stage = 'completion' group by task.id;
update public.crm_task_images image set submission_id = submission.id
from public.crm_task_submissions submission where submission.task_id = image.task_id and image.stage = 'completion';
update public.crm_assigned_tasks set status = 'submitted', completed_at = null
where id in (select task_id from public.crm_task_submissions);
alter table public.crm_task_images add constraint crm_task_image_stage_submission_check
  check ((stage = 'assignment' and submission_id is null) or (stage = 'completion' and submission_id is not null));
create index crm_task_images_submission_idx on public.crm_task_images(submission_id) where submission_id is not null;

create or replace function public.crm_save_task_photos(
  p_task_id bigint, p_actor uuid, p_stage text, p_values jsonb, p_images jsonb
) returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  actor public.profiles%rowtype;
  task public.crm_assigned_tasks%rowtype;
  image jsonb;
  submission_id bigint;
  latest_id bigint;
  image_count integer;
begin
  select * into actor from public.profiles where id = p_actor and active;
  if not found then raise exception 'Active account required.' using errcode = '42501'; end if;
  if p_stage is null or p_stage not in ('assignment', 'completion') then
    raise exception 'Invalid photo stage.' using errcode = '22023';
  end if;
  if p_stage = 'assignment' and actor.role not in ('admin', 'super_admin') then
    raise exception 'Administrator access required.' using errcode = '42501';
  end if;
  if jsonb_typeof(p_images) is distinct from 'array' then
    raise exception 'Invalid photos.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_images) > 10 then raise exception 'Upload up to 10 photos per submission.' using errcode = '22023'; end if;
  if p_task_id is null then
    if p_stage <> 'assignment' then raise exception 'Task not found.' using errcode = 'P0002'; end if;
    if not exists (select 1 from public.profiles where id = (p_values->>'assignee')::uuid
      and active and role not in ('admin', 'super_admin')) then
      raise exception 'Choose an active user.' using errcode = '22023';
    end if;
    insert into public.crm_assigned_tasks(assignee_id, assigned_by_id, title, note, due_at)
    values ((p_values->>'assignee')::uuid, p_actor, trim(p_values->>'title'),
      coalesce(p_values->>'note', ''), nullif(p_values->>'due_at', '')::timestamptz) returning * into task;
  else
    select * into task from public.crm_assigned_tasks where id = p_task_id for update;
    if not found or (p_stage = 'completion' and task.assignee_id <> p_actor) then
      raise exception 'Task not found.' using errcode = 'P0002';
    end if;
  end if;

  if p_stage = 'assignment' then
    if p_values ? 'status' then raise exception 'Use Approve or Reject to review a submission.' using errcode = '22023'; end if;
    if exists (select 1 from public.crm_task_submissions where task_id = task.id) then
      raise exception 'Instructions and Before photos cannot be changed after submission.' using errcode = '40001';
    end if;
    select count(*) into image_count from public.crm_task_images where task_id = task.id and stage = 'assignment';
    if image_count + jsonb_array_length(p_images) > 10 then
      raise exception 'Upload up to 10 Before photos.' using errcode = '22023';
    end if;
  else
    if task.status not in ('pending', 'rejected') then
      raise exception 'This task is already submitted or approved. Wait for the admin review.' using errcode = '40001';
    end if;
    -- Older clients send done; it now means submitted, never admin approval.
    if p_values ? 'status' and p_values->>'status' not in ('submitted', 'done') then
      raise exception 'Submit this task for admin review.' using errcode = '22023';
    end if;
    if task.status = 'rejected' then
      select max(id) into latest_id from public.crm_task_submissions where task_id = task.id;
      if nullif(p_values->>'previous_submission_id', '')::bigint is distinct from latest_id then
        raise exception 'The review has changed. Load the latest task before resubmitting.' using errcode = '40001';
      end if;
    end if;
    if jsonb_array_length(p_images) = 0 and (task.status = 'rejected' or
      exists (select 1 from public.crm_task_images where task_id = task.id and stage = 'assignment')) then
      raise exception 'Upload new After photos before submitting this task for review.' using errcode = '22023';
    end if;
    insert into public.crm_task_submissions(task_id, submitted_by, note)
    values (task.id, p_actor, trim(coalesce(p_values->>'submission_note', ''))) returning id into submission_id;
  end if;

  for image in select value from jsonb_array_elements(p_images) loop
    if image->>'storage_path' is null or image->>'storage_path' not like p_actor::text || '/%'
      or nullif(image->>'original_name', '') is null then
      raise exception 'Invalid photo metadata.' using errcode = '22023';
    end if;
    insert into public.crm_task_images(task_id, stage, uploaded_by, storage_path, original_name, submission_id)
    values (task.id, p_stage, p_actor, image->>'storage_path', image->>'original_name', submission_id);
  end loop;
  update public.crm_assigned_tasks set
    title = case when p_stage = 'assignment' and p_values ? 'title' then trim(p_values->>'title') else task.title end,
    note = case when p_stage = 'assignment' and p_values ? 'note' then coalesce(p_values->>'note', '') else task.note end,
    due_at = case when p_stage = 'assignment' and p_values ? 'due_at' then nullif(p_values->>'due_at', '')::timestamptz else task.due_at end,
    status = case when p_stage = 'completion' then 'submitted' else task.status end,
    completed_at = case when p_stage = 'completion' then null else task.completed_at end
  where id = task.id returning * into task;
  return to_jsonb(task);
end;
$$;

create function public.crm_review_task_submission(
  p_task_id bigint, p_submission_id bigint, p_actor uuid, p_action text, p_note text
) returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare task public.crm_assigned_tasks%rowtype; latest_id bigint;
begin
  if not exists (select 1 from public.profiles where id = p_actor and active and role in ('admin', 'super_admin')) then
    raise exception 'Administrator access required.' using errcode = '42501';
  end if;
  if p_action is null or p_action not in ('approve', 'reject') then
    raise exception 'Choose Approve or Reject.' using errcode = '22023';
  end if;
  if p_action = 'reject' and nullif(trim(p_note), '') is null then
    raise exception 'Add a rejection note explaining what needs arranging again.' using errcode = '22023';
  end if;
  select * into task from public.crm_assigned_tasks where id = p_task_id for update;
  if not found then raise exception 'Task not found.' using errcode = 'P0002'; end if;
  select max(id) into latest_id from public.crm_task_submissions where task_id = task.id;
  if task.status <> 'submitted' or p_submission_id is distinct from latest_id then
    raise exception 'This submission has changed or has already been reviewed. Load the latest task.' using errcode = '40001';
  end if;
  update public.crm_task_submissions set
    status = case when p_action = 'approve' then 'approved' else 'rejected' end,
    review_note = trim(coalesce(p_note, '')), reviewed_by = p_actor, reviewed_at = now()
  where id = p_submission_id and task_id = task.id;
  update public.crm_assigned_tasks set
    status = case when p_action = 'approve' then 'done' else 'rejected' end,
    completed_at = case when p_action = 'approve' then now() else null end
  where id = task.id returning * into task;
  return to_jsonb(task);
end;
$$;
