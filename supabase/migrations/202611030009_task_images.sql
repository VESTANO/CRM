-- Task photos are served only by the authenticated CRM API using signed URLs.
create table public.crm_task_images (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.crm_assigned_tasks(id) on delete cascade,
  stage text not null check (stage in ('assignment', 'completion')),
  uploaded_by uuid references auth.users(id) on delete set null,
  storage_path text not null unique,
  original_name text not null,
  uploaded_at timestamptz not null default now()
);
create index crm_task_images_task_stage_idx on public.crm_task_images(task_id, stage, id);
alter table public.crm_task_images enable row level security;
revoke all on public.crm_task_images from public, anon, authenticated;
grant all on public.crm_task_images to service_role;
grant usage, select on sequence public.crm_task_images_id_seq to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('crm-task-images', 'crm-task-images', false, 10485760,
  array['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/bmp', 'image/avif']);

-- Metadata and status commit together, after Storage has accepted every file.
-- The row lock also prevents concurrent uploads exceeding the per-stage limit.
create function public.crm_save_task_photos(
  p_task_id bigint, p_actor uuid, p_stage text, p_values jsonb, p_images jsonb
) returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  actor public.profiles%rowtype;
  task public.crm_assigned_tasks%rowtype;
  image jsonb;
  next_status text;
  image_count integer;
begin
  select * into actor from public.profiles where id = p_actor and active;
  if not found then raise exception 'Active account required.' using errcode = '42501'; end if;
  if p_stage not in ('assignment', 'completion') or p_stage is null then
    raise exception 'Invalid photo stage.' using errcode = '22023';
  end if;
  if p_stage = 'assignment' and actor.role not in ('admin', 'super_admin') then
    raise exception 'Administrator access required.' using errcode = '42501';
  end if;
  if jsonb_typeof(p_images) is distinct from 'array' or jsonb_array_length(p_images) > 10 then
    raise exception 'Upload up to 10 photos per stage.' using errcode = '22023';
  end if;

  if p_task_id is null then
    if p_stage <> 'assignment' then raise exception 'Task not found.' using errcode = 'P0002'; end if;
    if not exists (select 1 from public.profiles where id = (p_values->>'assignee')::uuid
      and active and role not in ('admin', 'super_admin')) then
      raise exception 'Choose an active user.' using errcode = '22023';
    end if;
    insert into public.crm_assigned_tasks(assignee_id, assigned_by_id, title, note, due_at)
    values ((p_values->>'assignee')::uuid, p_actor, trim(p_values->>'title'),
      coalesce(p_values->>'note', ''), nullif(p_values->>'due_at', '')::timestamptz)
    returning * into task;
  else
    select * into task from public.crm_assigned_tasks where id = p_task_id for update;
    if not found or (p_stage = 'completion' and task.assignee_id <> p_actor) then
      raise exception 'Task not found.' using errcode = 'P0002';
    end if;
  end if;

  select count(*) into image_count from public.crm_task_images where task_id = task.id and stage = p_stage;
  if image_count + jsonb_array_length(p_images) > 10 then
    raise exception 'Upload up to 10 photos per stage.' using errcode = '22023';
  end if;
  for image in select value from jsonb_array_elements(p_images) loop
    -- Paths are generated by the API, scoped to the authenticated uploader.
    if image->>'storage_path' is null or image->>'storage_path' not like p_actor::text || '/%'
      or nullif(image->>'original_name', '') is null then
      raise exception 'Invalid photo metadata.' using errcode = '22023';
    end if;
    insert into public.crm_task_images(task_id, stage, uploaded_by, storage_path, original_name)
    values (task.id, p_stage, p_actor, image->>'storage_path', image->>'original_name');
  end loop;

  next_status := coalesce(p_values->>'status', task.status);
  if next_status not in ('pending', 'done') then
    raise exception 'Choose a valid task status.' using errcode = '22023';
  end if;
  if next_status = 'done'
    and exists (select 1 from public.crm_task_images where task_id = task.id and stage = 'assignment')
    and not exists (select 1 from public.crm_task_images where task_id = task.id and stage = 'completion') then
    raise exception 'Upload at least one After photo before completing this task.' using errcode = '22023';
  end if;
  update public.crm_assigned_tasks set
    title = case when p_stage = 'assignment' and p_values ? 'title' then trim(p_values->>'title') else task.title end,
    note = case when p_stage = 'assignment' and p_values ? 'note' then coalesce(p_values->>'note', '') else task.note end,
    due_at = case when p_stage = 'assignment' and p_values ? 'due_at' then nullif(p_values->>'due_at', '')::timestamptz else task.due_at end,
    status = next_status,
    completed_at = case when next_status = 'done' then coalesce(task.completed_at, now()) else null end
  where id = task.id returning * into task;
  return to_jsonb(task);
end;
$$;
revoke all on function public.crm_save_task_photos(bigint, uuid, text, jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.crm_save_task_photos(bigint, uuid, text, jsonb, jsonb) to service_role;
