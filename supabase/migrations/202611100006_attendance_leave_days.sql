-- Approved leave is recorded per employee and date so attendance exports can
-- distinguish an absence from a declared leave day.
begin;

create table if not exists public.attendance_leave_days (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  leave_date date not null,
  reason text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (user_id, leave_date)
);

create index if not exists attendance_leave_days_user_date_idx
  on public.attendance_leave_days(user_id, leave_date desc);

alter table public.attendance_leave_days enable row level security;
revoke all on public.attendance_leave_days from public, anon, authenticated;
grant all on public.attendance_leave_days to service_role;
grant usage, select on sequence public.attendance_leave_days_id_seq to service_role;

commit;
